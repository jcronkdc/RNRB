export function FooterSection({ content, theme, socialLinks, siteName }: FooterSectionProps) {
  const { copyright, showPoweredBy = true, links = [] } = content;

  const accentColor = (theme.accentColor as string) || '#ff6347';
  const year = new Date().getFullYear();
  const copyrightText = copyright || `© ${year} ${siteName || 'Artist'}. All rights reserved.`;

  return (
    <footer
      className="px-4 py-12"
      style={{ backgroundColor: (theme.primaryColor as string) || '#000' }}
    >
      <div className="mx-auto max-w-6xl">
        <div className="flex flex-col items-center gap-8">
          {/* Social Links */}
          {socialLinks && Object.keys(socialLinks).length > 0 && (
            <motion.div
              initial={{ opacity: 0, y: 20 }}
              whileInView={{ opacity: 1, y: 0 }}
              viewport={{ once: true }}
              className="flex items-center gap-4"
            >
              {Object.entries(socialLinks).map(([platform, url]) => {
                if (!url) return null;
                return (
                  <a
                    key={platform}
                    href={url as string}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="rounded-full p-3 transition-all hover:scale-110"
                    style={{
                      backgroundColor: (theme.secondaryColor as string) || '#1a1a1a',
                      color: (theme.textColor as string) || '#fff',
                    }}
                    onMouseEnter={(e) => {
                      e.currentTarget.style.backgroundColor = accentColor;
                    }}
                    onMouseLeave={(e) => {
                      e.currentTarget.style.backgroundColor =
                        (theme.secondaryColor as string) || '#1a1a1a';
                    }}
                  >
                    {socialIcons[platform.toLowerCase()] || (
                      <span className="text-sm">{platform[0].toUpperCase()}</span>
                    )}
                  </a>
                );
              })}
            </motion.div>
          )}

          {/* Footer Links */}
          {links.length > 0 && (
            <div className="flex flex-wrap items-center justify-center gap-6">
              {links.map((link, index) => (
                <a
                  key={index}
                  href={link.url}
                  className="text-sm transition-colors hover:opacity-80"
                  style={{ color: (theme.mutedColor as string) || '#888' }}
                >
                  {link.label}
                </a>
              ))}
            </div>
          )}

          {/* Divider */}
          <div
            className="h-px w-24"
            style={{ backgroundColor: (theme.mutedColor as string) + '30' || '#333' }}
          />

          {/* Copyright */}
          <p
            className="text-center text-sm"
            style={{ color: (theme.mutedColor as string) || '#888' }}
          >
            {copyrightText}
          </p>

          {/* Powered By */}
          {showPoweredBy && (
            <a
              href="https://cronkwaters.com"
              target="_blank"
              rel="noopener noreferrer"
              className="text-xs transition-colors hover:opacity-80"
              style={{ color: (theme.mutedColor as string) + '80' || '#666' }}
            >
              Powered by CronkWaters
            </a>
          )}
        </div>
      </div>
    </footer>
  );
}
