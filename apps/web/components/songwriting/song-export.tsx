'use client';

import { Document, Page, Text, View, StyleSheet, pdf } from '@react-pdf/renderer';
import { AnimatePresence, motion } from 'framer-motion';
import { Download, FileText, Printer, Copy, Check, X, Music } from '@/components/ui/custom-icons';
import { useState } from 'react';

type SongBlock = {
  id: string;
  type: 'verse' | 'chorus' | 'bridge' | 'pre-chorus' | 'intro' | 'outro' | 'chord';
  content: string;
  chord?: string;
};

type SongExportProps = {
  isOpen: boolean;
  onClose: () => void;
  songTitle: string;
  artist?: string;
  key?: string;
  tempo?: number;
  timeSignature?: string;
  lyrics?: string;
  blocks?: SongBlock[];
  chords?: string[];
};

